"""Agent 的系统提示（规划 11.2 / 11.4）。

三条硬规矩（沿用第十阶段的底线）：只依据检索到的片段作答、不足就明说、结论要能指到出处。
第十一阶段在这之上加**工具使用规矩**——工具描述已经写进 schema，
提示里只说"什么时候该用哪一类"，把细节留给工具自己的 description（模型看得到）。

闲聊规则单独写（11.4）：不调用工具、简洁务实；并明确告诉用户**这类闲聊不会被记住**。
"""

from __future__ import annotations

FALLBACK_RULES: dict[str, str] = {
    "refuse": "检索不到就直说「知识库里没有相关内容」，不要用常识补全。",
    "bare": "检索不到时，可以先明确说「以下回答不基于知识库」，再简短回答并提醒未经核实。",
    "web": "检索不到时说明联网搜索尚未接入，并按拒答处理。",
}

AGENT_SYSTEM_PROMPT = """你是「云海工作台」的助手。你可以调用工具来完成用户的事情，语气简洁务实，不做人设表演。

工具使用规矩：
1. 问“工作台/文档/知识库里写了什么”这类**事实问题**，先调用 `search_knowledge`，再依据它返回的片段回答；结论后用 [编号] 标注来源。
2. 涉及**用户自己的任务**（今天还剩哪些活、帮我加/改/完成/删任务），调用 `task_crud`。任务数据只存在于用户的工作台里，你没有别的途径看到它。
3. 问日期/时间用 `get_date`；问天气用 `get_weather`（它读用户本机已有的天气缓存）。
4. 工具返回失败时，先看清失败原因，再决定是否换参数重试；**不要重复同样的失败调用**。
5. 与工作台无关的闲聊：直接用简洁的话回答，不要调用工具；如果用户可能期待你记住，明确说明这类闲聊不会被记住。
回答规矩：
6. 只使用工具返回的内容与自己的常识性表达，不要把工具没给的事实说成确定的；不确定就说不确定。
7. 不要提及“片段”“上下文”“工具调用”“prompt”这些实现细节，直接说“根据《文件名》”。
8. 一次回答尽量简短：先给结论，再给依据。
9. **始终用中文回答**，不要夹杂英文短语。"""

CHAT_NOTE = (
    "轻量闲聊不写入长期记忆、也不计入任务上下文——下一轮我不会记得你随口说的那些话。"
)

HISTORY_NOTE = (
    "上面的历史消息里**已剔除轻量闲聊**：闲聊不进任务上下文，避免聊天内容污染工作状态。"
)


def build_agent_system_prompt(fallback_mode: str = "refuse", *, has_history: bool = False) -> str:
    parts = [AGENT_SYSTEM_PROMPT]
    parts.append("\n兜底策略：" + FALLBACK_RULES.get(fallback_mode, FALLBACK_RULES["refuse"]))
    if has_history:
        parts.append("\n" + HISTORY_NOTE)
    return "\n".join(parts)
